import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IMAGE_DIR = path.join(ROOT, 'images');
const OUT_FILE = path.join(ROOT, 'assets', 'data', 'images.js');
const MASTER_LIST_FILE = path.join(ROOT, 'docs', 'chinese-color-master-list.md');
const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp']);

// Each image is named NNN-色名.ext. The NNN prefix is the color's STABLE id —
// never re-derive it from directory sort position, or inserting/removing a file
// would silently renumber every color after it (and every SEO URL keyed off id).
function parseImageName(file) {
  const match = file.match(/^(\d{3})-(.+)\.[^.]+$/);
  return match ? { id: match[1], name: match[2] } : null;
}

// The master list is the canonical, ordered 742-color source of truth.
async function loadMasterList() {
  const content = await readFile(MASTER_LIST_FILE, 'utf8');
  const entries = [];

  for (const line of content.split(/\r?\n/)) {
    const match = line.trim().match(/^(.+?)\s+(#[0-9A-Fa-f]{6})$/);
    if (match) entries.push({ name: match[1], hex: match[2].toUpperCase() });
  }

  return entries;
}

async function collectImages(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;

    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await collectImages(fullPath));
      continue;
    }

    if (entry.isFile() && IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      const info = await stat(fullPath);
      files.push({
        path: path.relative(ROOT, fullPath).split(path.sep).join('/'),
        file: entry.name,
        size: info.size,
      });
    }
  }

  return files;
}

const master = await loadMasterList();
const images = (await collectImages(IMAGE_DIR)).sort((a, b) => a.path.localeCompare(b.path, 'zh-Hans-CN'));
const totalBytes = images.reduce((total, image) => total + image.size, 0);
const generatedAt = new Date().toISOString();

// Join each image to the master list by its stable id, asserting the contract
// the README promises (NNN-色名 == master-list[NNN]). Any violation aborts the
// build with a precise message instead of silently writing hex: null.
const errors = [];
const seenIds = new Set();
const payload = [];

if (images.length !== master.length) {
  errors.push(`count mismatch: ${images.length} images vs ${master.length} master-list entries`);
}

for (const image of images) {
  const parsed = parseImageName(image.file);
  if (!parsed) {
    errors.push(`filename "${image.file}" must match NNN-色名.ext`);
    continue;
  }
  const { id, name } = parsed;
  if (seenIds.has(id)) errors.push(`duplicate id ${id} (${image.file})`);
  seenIds.add(id);

  const entry = master[Number(id) - 1];
  if (!entry) {
    errors.push(`No.${id} ${image.file}: no master-list entry at position ${id}`);
    continue;
  }
  if (entry.name !== name) {
    errors.push(`name drift No.${id}: file="${name}" but master-list[#${id}]="${entry.name}"`);
  }
  payload.push({ id, hex: entry.hex, ...image });
}

for (let i = 1; i <= images.length; i += 1) {
  const id = String(i).padStart(3, '0');
  if (!seenIds.has(id)) errors.push(`missing id in sequence: expected ${id}`);
}

if (errors.length) {
  console.error(
    'build-manifest: refusing to write — manifest contract violated:\n'
    + errors.map((e) => `  - ${e}`).join('\n'),
  );
  process.exit(1);
}

// Deterministic output order by stable id (matches the path sort for NNN- names).
payload.sort((a, b) => a.id.localeCompare(b.id));

const js = `/* Generated by scripts/build-manifest.mjs. Do not edit by hand. */
window.TRADITIONAL_COLOR_PROJECT = ${JSON.stringify({
  count: payload.length,
  totalBytes,
  generatedAt,
  archiveName: 'zhongguo-traditional-colors-images.zip',
}, null, 2)};

window.TRADITIONAL_COLOR_IMAGES = ${JSON.stringify(payload, null, 2)};
`;

await writeFile(OUT_FILE, js, 'utf8');
console.log(`Wrote ${payload.length} images to ${path.relative(ROOT, OUT_FILE)}`);
